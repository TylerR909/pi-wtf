/** How long a clicker quip stays up. Slightly longer lines linger; tiny jitter. */
export function clickerDwellMs(text: string, rng = Math.random): number {
  const jitter = (rng() * 2 - 1) * 180;
  // Short line (~20 chars) lands around 2.8–3.2s; longer roasts linger a bit more.
  return Math.round(2650 + text.length * 20 + jitter);
}
