/** Pick a quip. Intensity 0–1 biases toward later (more unhinged) entries. */
export function pickQuip(intensity: number, rng = Math.random): string {
  const n = SPACEBAR_QUIPS.length;
  if (n === 0) return "...";
  const t = Math.min(1, Math.max(0, intensity));
  // Weight toward the end as intensity rises; still allow early quips.
  const min = Math.floor(t * n * 0.55);
  const idx = min + Math.floor(rng() * (n - min));
  return SPACEBAR_QUIPS[Math.min(idx, n - 1)]!;
}
